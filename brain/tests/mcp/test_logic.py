GCODE = """
; generated by PrusaSlicer
M83
M104 S240
M140 S85
G92 E0
;LAYER_CHANGE
;TYPE:Perimeter
G1 X10 Y0 E0.5 F1200
G1 E-0.8 F2100
G1 X20 Y0 E0.5
;TYPE:Bridge infill
G1 X32 Y0 E0.6
G1 X36 Y0 E0.2
;TYPE:Support material
G1 X40 Y0 E1.0
M109 S255
;LAYER_CHANGE
; filament used [mm] = 1234.5
; filament used [g] = 3.7
; total layers count = 2
; estimated printing time (normal mode) = 1h 30m 0s
"""


def test_gcode_report_fields():
    report = gcode.parse(GCODE)
    assert report["time_h"] == 1.5
    assert report["filament_g"] == 3.7 and report["filament_mm"] == 1234.5
    assert report["layer_count"] == 2
    assert report["max_temp_c"] == 255  # hotend, not bed
    assert report["retractions"] == 1
    assert report["max_bridge_mm"] == 12.0  # over the 10 mm DFM limit of SPEC 12.3
    assert report["support_volume_mm3"] == pytest.approx(1.0 * 2.405, rel=1e-3)


async def test_estimate_prices_the_print(tmp_path):
    path = tmp_path / "part.gcode"
    path.write_text(GCODE, encoding="utf-8")
    estimate = await fab.estimate(str(path))
    assert estimate["time_h"] == 1.5
    assert estimate["cost_try"] == round(3.7 * fab.FILAMENT_TRY_PER_G, 2)


async def test_validate_gcode_renders_the_approval_preview(tmp_path, monkeypatch):
    path = tmp_path / "part.gcode"
    path.write_text(GCODE, encoding="utf-8")
    argv_seen = []

    async def fake_runner(argv, timeout_s):
        argv_seen.append(argv)
        # The real prusa-gcodeviewer writes the PNG named after --export-png.
        # validate_gcode refuses a report with no preview (SPEC 6.4 mode 2), so a
        # double that returns cleanly without producing the file is not the tool.
        Path(argv[argv.index("--export-png") + 1]).write_bytes(b"\x89PNG\r\n\x1a\n")
        return ""

    monkeypatch.setenv("PRUSA_GCODEVIEWER_BIN", "prusa-gcodeviewer")
    fab.configure(runner=fake_runner)
    report = await fab.validate_gcode(str(path))

    assert report.preview_png.endswith(".png")  # SPEC 12.4: shown on the mobile approval screen
    assert argv_seen[0][:2] == [
        "prusa-gcodeviewer",
        "--export-png",
    ]  # SPEC 6.4 CLI, subprocess only
    assert report.layer_count == 2 and report.retractions == 1
