class FakeLock:
    def __init__(self):
        self.events = []

    async def acquire(self, consumer, timeout_s=300):
        self.events.append(("acquire", consumer))

    async def release(self, consumer):
        self.events.append(("release", consumer))


class FakeRunner:
    def __init__(self, replies=None):
        self.replies = replies or {}
        self.calls = []

    async def call(self, op, payload, timeout_s):
        self.calls.append((op, timeout_s))
        reply = self.replies.get(op, {})
        return reply(payload) if callable(reply) else reply


