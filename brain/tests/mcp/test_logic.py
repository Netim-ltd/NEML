async def test_visual_profile_takes_and_releases_the_gpu_mutex(world):
    runner, lock, _ = world
    handle = await sim.load_world("flat", 42, "visual")
    assert lock.events == [("acquire", "gazebo")]  # SPEC 4.5: vLLM must stop first
    await sim.teardown(handle)
    assert lock.events == [("acquire", "gazebo"), ("release", "gazebo")]


async def test_fast_profile_never_touches_the_gpu(world):
    runner, lock, _ = world
    handle = await sim.load_world("flat", 42, "fast")
    await sim.teardown(handle)
    assert lock.events == []


async def test_metrics_flag_a_run_that_drifts_more_than_two_percent(world):
    runner, _, urdf = world
    values = {"distance_m": 2.0, "energy_wh": 1.0}
    runner.replies["metrics"] = lambda _payload: {"values": dict(values)}
    await sim.load_world("flat", 42, "fast")
    robot = await sim.spawn_robot(urdf, sim.Pose(), "r1")

    first = await sim.get_metrics(robot)
    assert first.deterministic and first.seed == 42 and len(first.sim_version) == 12
    assert (await sim.get_metrics(robot)).deterministic  # same seed + version -> same result

    values["distance_m"] = 2.06  # +3%, over the 2% tolerance of SPEC 11.2
    runner.replies["metrics"] = lambda _payload: {"values": dict(values)}
    assert (await sim.get_metrics(robot)).deterministic is False


async def test_sensor_without_an_si_unit_is_refused(world):
    runner, _, urdf = world
    runner.replies["sensor"] = {"values": [0.1, 0.2, 0.3], "sim_time_s": 1.0}
